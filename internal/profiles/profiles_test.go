func TestProfileRelationRejectsMismatchedEvidence(t *testing.T) {
	rows := recordingtest.Results("X", []float64{1})
	fp := recordingtest.Defaults().Fingerprint
	c := Capture{Fingerprint: fp, MeasurementRevision: Revision(rows), Children: []Child{{Name: string(rows[0].Name), Iterations: 1}}}
	if err := Relation(c, rows, fp); err != nil {
		t.Fatal(err)
	}
	for _, change := range []func(*Capture){
		func(c *Capture) { c.MeasurementRevision = Digest([]byte("other revision")) },
		func(c *Capture) { c.Fingerprint.MaximalClosure += "moved" },
		func(c *Capture) { c.Fingerprint.TestVariantClosure += "moved" },
		func(c *Capture) { c.Fingerprint.Guards.BuildConfig += "moved" },
		func(c *Capture) { c.Fingerprint.Guards.RuntimeConfig += "moved" },
		func(c *Capture) { c.Children = []Child{{Name: "Y-8", Iterations: 1}} },
		func(c *Capture) { c.Children = nil },
	} {
		bad := c
		change(&bad)
		if err := Relation(bad, rows, fp); err == nil {
			t.Fatalf("mismatched relation accepted: %+v", bad)
		}
	}
}

func TestProfileRelationRequiresProvenApplicability(t *testing.T) {
	rows := recordingtest.Results("X", []float64{1})
	fp := recordingtest.Defaults().Fingerprint
	c := Capture{Fingerprint: fp, MeasurementRevision: Revision(rows), Children: []Child{{Name: string(rows[0].Name), Iterations: 1}}}
	c.Fingerprint.TestVariantClosure = "current"
	for _, strategy := range []string{gofresh.InertTestVariantExtension, "unknown", ""} {
		fp.InertTestVariantApplicability = gofresh.InertTestVariantApplicability{Strategy: strategy, TestVariantClosure: "current"}
		if err := Relation(c, rows, fp); !errors.Is(err, ErrRelationUnproven) || errors.Is(err, ErrRelationMismatch) {
			t.Fatalf("unproven %q endpoint accepted", strategy)
		}
		if err := CheckedRelation(t.Context(), c, rows, fp, nil); !errors.Is(err, ErrRelationUnproven) || errors.Is(err, ErrRelationMismatch) {
			t.Fatalf("nil view conferred %q applicability", strategy)
		}
	}
}

func TestRelationErrorClasses(t *testing.T) {
	rows := recordingtest.Results("X", []float64{1})
	fp := recordingtest.Defaults().Fingerprint
	fp.InertTestVariantApplicability = gofresh.InertTestVariantApplicability{Strategy: gofresh.InertTestVariantExtension, TestVariantClosure: "current"}
	c := Capture{Fingerprint: fp, MeasurementRevision: Revision(rows), Children: []Child{{Name: string(rows[0].Name), Iterations: 1}}}
	for _, mutate := range []func(*Capture){
		func(c *Capture) { c.MeasurementRevision = "different" },
		func(c *Capture) { c.Children = nil },
		func(c *Capture) { c.Fingerprint.Guards.RuntimeConfig += "different" },
	} {
		bad := c
		mutate(&bad)
		if err := CheckedRelation(t.Context(), bad, rows, fp, nil); !errors.Is(err, ErrRelationMismatch) || errors.Is(err, ErrRelationUnproven) {
			t.Fatalf("pair contradiction masked by missing proof: %v", err)
		}
	}
	unavailable := fmt.Errorf("proof: %w", gofresh.ErrAnalysisUnavailable)
	if err := applicabilityFailure(unavailable); !errors.Is(err, ErrRelationUnproven) || !errors.Is(err, gofresh.ErrAnalysisUnavailable) || errors.Is(err, ErrRelationMismatch) {
		t.Fatalf("unavailable proof misclassified: %v", err)
	}
	for _, err := range []error{context.Canceled, gofresh.ErrViewChanged, errors.New("read failed")} {
		if got := applicabilityFailure(err); got != err || errors.Is(got, ErrRelationUnproven) || errors.Is(got, ErrRelationMismatch) {
			t.Fatalf("operational error misclassified: %v", got)
		}
	}
}
