func FuzzIndexAdmission(f *testing.F) {
	seed, err := Encode(testIndex(f))
	if err != nil {
		f.Fatal(err)
	}
	raw, err := base64.RawURLEncoding.DecodeString(seed)
	if err != nil {
		f.Fatal(err)
	}
	f.Add(string(raw))
	f.Add(`{"version":1,"captures":[]}`)
	f.Add(`{"version":1,"version":1,"captures":[]}`)
	f.Fuzz(func(t *testing.T, raw string) {
		encoded := base64.RawURLEncoding.EncodeToString([]byte(raw))
		if i, err := Decode(encoded); err == nil {
			back, err := Encode(i)
			if err != nil || back != encoded {
				t.Fatalf("noncanonical admitted: %s", raw)
			}
		}
	})
}

