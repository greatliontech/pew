func encodedProfile(t testing.TB, values ...int64) []byte {
	t.Helper()
	f := &profile.Function{ID: 1, Name: "example.com/p.Work", Filename: "/src/work.go", StartLine: 2}
	l := &profile.Location{ID: 1, Line: []profile.Line{{Function: f, Line: 3}}}
	p := &profile.Profile{SampleType: []*profile.ValueType{{Type: "cpu", Unit: "nanoseconds"}}, Function: []*profile.Function{f}, Location: []*profile.Location{l}, PeriodType: &profile.ValueType{Type: "cpu", Unit: "nanoseconds"}, Period: 10000000}
	for i, value := range values {
		s := &profile.Sample{Value: []int64{value}}
		if i%2 == 0 {
			s.Location = []*profile.Location{l}
		}
		p.Sample = append(p.Sample, s)
	}
	var b bytes.Buffer
	if err := p.Write(&b); err != nil {
		t.Fatal(err)
	}
	return b.Bytes()
}

func TestFlatWeightsConserveUnresolvedSamples(t *testing.T) {
	src := Source{Filename: "/src/work.go", ModuleRelative: "work.go", Package: "example.com/p", Bytes: []byte("package p\nfunc Work() {\n println(1)\n}\n")}
	metrics, err := Analyze(encodedProfile(t, 11, 13, 17), "cpu", []Source{src})
	if err != nil {
		t.Fatal(err)
	}
	m := metrics[0]
	if m.Total != 41 || len(m.Weights) != 2 {
		t.Fatalf("lost samples: %+v", m)
	}
	if m.Weights[0].Flat != 28 || m.Weights[0].Attribution != "exact-source" || m.Weights[1].Flat != 13 || m.Weights[1].Attribution != "unresolved" {
		t.Fatalf("false attribution: %+v", m)
	}
	for _, altered := range []Source{
		{Filename: "/other/work.go", ModuleRelative: "work.go", Package: src.Package, Bytes: src.Bytes},
		{Filename: src.Filename, ModuleRelative: "work.go", Package: src.Package, Bytes: []byte("package p\n//line work.go:2\nfunc Work() {}\n")},
		{Filename: src.Filename, ModuleRelative: "work.go", Package: src.Package, Bytes: []byte("// Code generated by generator. DO NOT EDIT.\npackage p\nfunc Work() {}\n")},
		{Filename: src.Filename, ModuleRelative: "work.go", Package: src.Package, Bytes: []byte("package p\nfunc Other() {\n println(1)\n}\n")},
	} {
		m, err := Analyze(encodedProfile(t, 7), "cpu", []Source{altered})
		if err != nil || m[0].Weights[0].Attribution != "unresolved" {
			t.Fatalf("guessed source: %+v %v", m, err)
		}
	}
}

func TestInlineLeafAndCumulativeOverlap(t *testing.T) {
	inner := &profile.Function{ID: 1, Name: "inline"}
	outer := &profile.Function{ID: 2, Name: "outer"}
	l := &profile.Location{ID: 1, Line: []profile.Line{{Function: inner}, {Function: outer}}}
	p := &profile.Profile{SampleType: []*profile.ValueType{{Type: "cpu", Unit: "nanoseconds"}}, Function: []*profile.Function{inner, outer}, Location: []*profile.Location{l}, Sample: []*profile.Sample{{Location: []*profile.Location{l, l}, Value: []int64{10}}}}
	var b bytes.Buffer
	if err := p.Write(&b); err != nil {
		t.Fatal(err)
	}
	m, err := Analyze(b.Bytes(), "cpu", nil)
	if err != nil {
		t.Fatal(err)
	}
	if m[0].Total != 10 || m[0].Weights[0].Symbol != "inline" || m[0].Weights[0].Flat != 10 || m[0].Weights[1].Flat != 0 || m[0].Weights[1].Cumulative != 10 {
		t.Fatalf("inline weights: %+v", m)
	}
}

func TestProfileRefusesCorruptionNegativeOverflowAndWrongKind(t *testing.T) {
	for _, b := range [][]byte{[]byte("corrupt"), encodedProfile(t, -1), encodedProfile(t, math.MaxInt64, 1)} {
		if _, err := Analyze(b, "cpu", nil); err == nil {
			t.Fatal("invalid samples admitted")
		}
	}
	if _, err := Analyze(encodedProfile(t, 1), "alloc", nil); err == nil {
		t.Fatal("cpu substituted for allocations")
	}
	m, err := Analyze(encodedProfile(t, 0), "cpu", nil)
	if err != nil || !Empty(m) {
		t.Fatalf("zero profile: %v %v", m, err)
	}
}

func FuzzProfileAccounting(f *testing.F) {
	f.Add([]byte{1, 2, 3, 0, 255})
	f.Fuzz(func(t *testing.T, values []byte) {
		var total int64
		v := make([]int64, len(values))
		for i, n := range values {
			v[i] = int64(n)
			total += int64(n)
		}
		metrics, err := Analyze(encodedProfile(t, v...), "cpu", nil)
		if err != nil {
			t.Fatal(err)
		}
		var flat int64
		for _, w := range metrics[0].Weights {
			flat += w.Flat
		}
		if flat != total || metrics[0].Total != total {
			t.Fatalf("flat=%d total=%d want=%d", flat, metrics[0].Total, total)
		}
	})
}

