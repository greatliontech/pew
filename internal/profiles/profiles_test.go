func TestIndexCanonicalRoundTripAndRefusals(t *testing.T) {
	i := testIndex(t)
	i.Captures[0].Fingerprint.ObservationAssertion = "historical-assertion"
	i.Captures[0].Sources = []Source{{Filename: "/source.go", ModuleRelative: "source.go", Package: "example.com/p", Bytes: []byte(strings.Repeat("// exact source bytes\n", 5000))}}
	encoded, err := Encode(i)
	if err != nil {
		t.Fatal(err)
	}
	got, err := Decode(encoded)
	if err != nil {
		t.Fatal(err)
	}
	if got.Captures[0].Fingerprint != i.Captures[0].Fingerprint || !bytes.Equal(got.Captures[0].Sources[0].Bytes, i.Captures[0].Sources[0].Bytes) {
		t.Fatal("native/source evidence changed")
	}
	rows := recordingtest.Results("X", []float64{1, 2})
	for _, row := range rows {
		row.Config = append(row.Config, run.KeyProfiles.Config(encoded))
	}
	st := store.New(t.TempDir())
	if err := st.Write("", "BenchmarkX", "", rows); err != nil {
		t.Fatal(err)
	}
	stored, err := st.ReadBytes(store.Key{Bench: "BenchmarkX"})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(stored, []byte(run.KeyProfiles.Name+".2: ")) {
		t.Fatal("large profile index was not chunked")
	}
	for _, line := range bytes.Split(stored, []byte{'\n'}) {
		if len(line) >= 64<<10 {
			t.Fatal("oversized benchmark-format line")
		}
	}
	back, err := st.Read("", "BenchmarkX", "")
	if err != nil {
		t.Fatal(err)
	}
	if back[0].GetConfig(run.KeyProfiles.Name) != encoded {
		t.Fatal("chunk round-trip changed index")
	}
	jsonBytes, err := base64.RawURLEncoding.DecodeString(encoded)
	if err != nil {
		t.Fatal(err)
	}
	for _, broken := range []string{
		strings.Replace(string(jsonBytes), `"version":1`, `"version":1,"version":1`, 1),
		strings.Replace(string(jsonBytes), `"version":1`, `"version":1,"unknown":true`, 1),
		strings.Replace(string(jsonBytes), `"dirty":false,`, "", 1),
		string(jsonBytes) + "{}",
		strings.Replace(string(jsonBytes), `"kind":"cpu"`, `"kind":"heap"`, 1),
	} {
		if _, err := Decode(base64.RawURLEncoding.EncodeToString([]byte(broken))); err == nil {
			t.Fatal("malformed index admitted")
		}
	}
	if _, err := Decode(encoded + "="); err == nil {
		t.Fatal("noncanonical base64 admitted")
	}
	// A canonical unknown/native field cannot be silently ignored on restore.
	var shape map[string]any
	if err := json.Unmarshal(jsonBytes, &shape); err != nil {
		t.Fatal(err)
	}
	shape["captures"].([]any)[0].(map[string]any)["fingerprint"].(map[string]any)["unknown"] = true
	broken, err := json.Marshal(shape)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := Decode(base64.RawURLEncoding.EncodeToString(broken)); err == nil {
		t.Fatal("native grammar bypassed")
	}
}

